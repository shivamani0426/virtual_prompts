import fs from "node:fs";
import path from "node:path";
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),"utf8");
const files=[["PAGE_HTML","public/index.html"],["PAGE_CSS","public/styles.css"],["PAGE_JS","public/app.js"]];
const prelude=files.map(([name,file])=>"const "+name+" = "+JSON.stringify(read(file))+";").join("\n");
const output=prelude+"\n"+read("src/worker.js")+"\n";
fs.mkdirSync(path.join(root,"dist"),{recursive:true});
fs.writeFileSync(path.join(root,"dist/worker.js"),output);
console.log("Built dist/worker.js ("+output.length+" characters).");
